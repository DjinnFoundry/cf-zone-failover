#!/usr/bin/env node
/**
 * This repository is public: it must hold no real domain, address, IP or
 * account id of whoever uses it. The check is an allowlist, so it can run in
 * public CI without naming what it protects: anything that is not
 * documentation data (RFC 2606 names, RFC 5737 IPs) or a known public service
 * fails.
 *
 * A private denylist (one literal or /regex/ per line, `#` for comments) can be
 * added with PUBLIC_DATA_DENYLIST=<path>. Keep that file outside the repo.
 *
 *   node scripts/public-data.mjs            # tracked files
 *   node scripts/public-data.mjs --authors  # also every commit author and committer
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

/** Public services the code and docs are allowed to name. */
const ALLOWED_HOSTS = new Set([
  'hayahora.futbol',
  'api.cloudflare.com',
  'cloudflare-dns.com',
  'dns.google',
  'github.com',
  'zetaread.com',
  'dgilperez.com',
  'pages.dev',
]);
/** RFC 2606 names, and Pages projects named like them (`example-docs.pages.dev`). */
const DOCUMENTATION_HOST = /(^|\.)(example\.(com|net|org)|example|test|invalid|localhost)$|^example[a-z0-9-]*\.pages\.dev$/;
/** Public resolvers, loopback and RFC 5737 documentation ranges. */
const ALLOWED_IP = /^(1\.1\.1\.1|8\.8\.8\.8|127\.0\.0\.1|0\.0\.0\.0|192\.0\.2\.\d+|198\.51\.100\.\d+|203\.0\.113\.\d+)$/;
const ALLOWED_EMAIL_DOMAIN = /(^|\.)(example\.(com|net|org)|example|test|invalid|users\.noreply\.github\.com)$/;

// Real TLDs only: `res.headers` or `config.js` are code, not hosts. `.site` is
// left out because `apis.site` is code too; the private denylist covers it.
const TLDS = 'com|net|org|io|dev|app|co|es|eu|uk|de|fr|it|pt|me|ai|xyz|info|biz|cloud|online|tech|futbol|google|example|test';
const HOST = new RegExp(`\\b((?:[a-z0-9-]+\\.)+(?:${TLDS}))\\b`, 'gi');
const EMAIL = /\b[A-Za-z0-9._%+-]+@([A-Za-z0-9.-]+\.[A-Za-z]{2,})\b/g;
const IPV4 = /\b(?:\d{1,3}\.){3}\d{1,3}\b/g;
/** Cloudflare account, zone and token ids. Commit SHAs (40) and hashes are longer. */
const HEX32 = /(?<![0-9a-f])[0-9a-f]{32}(?![0-9a-f])/gi;

/** Files that are not ours to police: generated by npm, or legal text. */
const SKIP = new Set(['package-lock.json', 'LICENSE']);

export function loadDenylist(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const re = line.match(/^\/(.+)\/([a-z]*)$/);
      return re ? new RegExp(re[1], re[2].includes('i') ? re[2] : `${re[2]}i`) : line.toLowerCase();
    });
}

/** Every leak in one file's text, as `file:line: what`. */
export function findLeaks(text, file, denylist = []) {
  const leaks = [];
  text.split('\n').forEach((line, i) => {
    const at = (what) => leaks.push(`${file}:${i + 1}: ${what}`);
    const emailDomains = new Set();
    for (const [, domain] of line.matchAll(EMAIL)) {
      emailDomains.add(domain.toLowerCase());
      if (!ALLOWED_EMAIL_DOMAIN.test(domain.toLowerCase())) at(`email on ${domain}`);
    }
    for (const [, host] of line.matchAll(HOST)) {
      const h = host.toLowerCase();
      if (emailDomains.has(h) || ALLOWED_HOSTS.has(h) || DOCUMENTATION_HOST.test(h)) continue;
      at(`host ${host}`);
    }
    for (const [ip] of line.matchAll(IPV4)) if (!ALLOWED_IP.test(ip)) at(`IP ${ip}`);
    for (const [id] of line.matchAll(HEX32)) at(`32-hex id ${id.slice(0, 6)}…`);
    const lower = line.toLowerCase();
    for (const entry of denylist) {
      const hit = typeof entry === 'string' ? lower.includes(entry) : entry.test(line);
      if (hit) at('private denylist entry');
    }
  });
  return leaks;
}

/** Author and committer emails must be GitHub noreply addresses. */
export function authorLeaks(emails) {
  return [...new Set(emails.filter(Boolean))]
    .filter((email) => !/@users\.noreply\.github\.com$/.test(email))
    .map((email) => `commit identity ${email.replace(/^[^@]*/, '…')} is not a GitHub noreply address`);
}

function main() {
  const git = (...args) => execFileSync('git', args, { encoding: 'utf8' });
  const denylistPath = process.env.PUBLIC_DATA_DENYLIST;
  const denylist = denylistPath ? loadDenylist(readFileSync(denylistPath, 'utf8')) : [];

  const files = git('ls-files', '-z').split('\0').filter((f) => f && !SKIP.has(f));
  const leaks = files.flatMap((file) => findLeaks(readFileSync(file, 'utf8'), file, denylist));
  if (process.argv.includes('--authors')) {
    leaks.push(...authorLeaks(git('log', '--format=%ae%n%ce').split('\n')));
  }
  // Locally, also the identity the next commit will get (in CI it is the runner's).
  if (!process.env.CI) {
    const next = git('var', 'GIT_AUTHOR_IDENT').match(/<([^>]+)>/)?.[1];
    if (next) leaks.push(...authorLeaks([next]));
  }

  if (leaks.length > 0) {
    console.error(`public-data: ${leaks.length} finding(s)\n${leaks.join('\n')}`);
    process.exit(1);
  }
  console.log(`public-data: ${files.length} files clean${denylist.length ? `, ${denylist.length} private entries checked` : ''}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
